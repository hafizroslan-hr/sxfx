export const GLYPH_W = 3;
export const GLYPH_H = 5;
export const ADVANCE = 4;

/** Glyph → 15-bit mask, row-major, bit 14 = top-left. */
export const GLYPHS: Record<string, number> = {};
for (const [ch, rows] of Object.entries(RAW)) {
  const bits = rows.replace(/ /g, '');
  if (bits.length !== 15) throw new Error(`bad glyph ${ch}`);
  let m = 0;
  for (let i = 0; i < 15; i++) if (bits[i] === '#') m |= 1 << (14 - i);
  GLYPHS[ch] = m;
}

export const textWidth = (s: string) => (s.length === 0 ? 0 : s.length * ADVANCE - 1);
